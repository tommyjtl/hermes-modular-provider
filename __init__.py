# Hermes' effort ladder, weakest first ("ultra" is Hermes-internal and maps to max).
_LADDER = ("none", "minimal", "low", "medium", "high", "xhigh", "max")


def _clamp(effort: str, supported: list[str]) -> str:
    """Nearest weaker supported level, never escalating; the lowest when none is weaker."""
    effort = "max" if effort == "ultra" else effort
    if effort in supported:
        return effort
    if effort not in _LADDER:
        return supported[0]
    weaker = [level for level in supported if _LADDER.index(level) < _LADDER.index(effort)]
    return weaker[-1] if weaker else supported[0]


def _reasoning(spec: dict, config: dict) -> dict:
    """The request's ``reasoning`` object for one model, or {} to leave the host default."""
    effort = str(config.get("effort") or "").strip().lower()
    if config.get("enabled") is False or effort == "none":
        if spec["off"] == "toggle":
            return {"enabled": False}
        if spec["off"] == "effort":
            return {"effort": "none"}
        # This model can't turn thinking off here: send the lightest setting instead.
        return {"effort": spec["efforts"][0]} if spec["efforts"] else {}
    if spec["efforts"] and effort:
        return {"effort": _clamp(effort, spec["efforts"])}
    return {"enabled": True} if spec["toggle"] else {}


class ModularProfile(ProviderProfile):
    """Modular Cloud: OpenAI-compatible chat completions with a nested ``reasoning`` object."""

    def fetch_models(self, **kwargs: Any) -> list[str] | None:
        # GET /v1/models also lists models without published prices; offer only the ones here.
        live = super().fetch_models(**kwargs)
        return None if live is None else [model for model in live if model in MODELS]

    def build_api_kwargs_extras(
        self, *, reasoning_config: dict | None = None, model: str | None = None, **context: Any
    ) -> tuple[dict[str, Any], dict[str, Any]]:
        spec = (MODELS.get(model or "") or {}).get("reasoning")
        if not spec or not isinstance(reasoning_config, dict):
            return {}, {}
        reasoning = _reasoning(spec, reasoning_config)
        return ({"reasoning": reasoning} if reasoning else {}), {}


